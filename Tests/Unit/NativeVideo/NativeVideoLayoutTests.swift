import AVFoundation
import XCTest

@testable import WallpaperMachine

/// Where the native backend puts the picture, against the numbers the
/// Compatibility backend's own layout code produces.
///
/// Pure arithmetic: no player, no media (one test draws plain layers to pin the
/// vertical convention). Whether the real player layer then
/// lands there is in `NativeVideoPlayerMediaTests`, which is opt-in.
final class NativeVideoLayoutTests: XCTestCase {
    private struct Golden {
        var name: String
        var mode: NativeVideoScalingMode
        var factor: Double
        var video: CGSize
        /// The display in points.
        var viewport: CGSize
        var scale: CGFloat
        var expected: NativeVideoLayout.PixelRect
    }

    private func rect(_ x: Int, _ y: Int, _ width: Int, _ height: Int) -> NativeVideoLayout.PixelRect {
        NativeVideoLayout.PixelRect(x: x, y: y, width: width, height: height)
    }

    /// Generated by compiling the renderer's `WallpaperScaling.cpp` (it needs
    /// no GPU header) and printing `ComputeWallpaperScalingLayout`'s
    /// `viewport_px`, with the display handed over in device pixels the way
    /// the renderer does (see docs/testing/coverage.md#nativevideo). They are
    /// not derived by hand, so a wrong rounding rule or an operation order
    /// that moves a tie fails here instead of on someone's display.
    private var golden: [Golden] {
        let hd = CGSize(width: 1920, height: 1080)
        let laptop = CGSize(width: 1512, height: 982)
        return [
            Golden(name: "fit", mode: .match, factor: 1, video: hd, viewport: laptop, scale: 2,
                expected: rect(0, 132, 3024, 1701)),
            Golden(name: "fill", mode: .fill, factor: 1, video: hd, viewport: laptop, scale: 2,
                expected: rect(-234, 0, 3492, 1964)),
            Golden(name: "stretch", mode: .stretch, factor: 1, video: hd, viewport: laptop, scale: 2,
                expected: rect(0, 0, 3024, 1964)),
            // One video pixel is one point: 1920x1080 points, 3840x2160 device pixels.
            Golden(name: "original size", mode: .none, factor: 1, video: hd, viewport: laptop,
                scale: 2, expected: rect(-408, -98, 3840, 2160)),
            Golden(name: "fit, portrait clip on a landscape display", mode: .match, factor: 1,
                video: CGSize(width: 1080, height: 1920), viewport: CGSize(width: 1920, height: 1080),
                scale: 1, expected: rect(656, 0, 608, 1080)),
            Golden(name: "fill zoomed in", mode: .fill, factor: 1.25, video: hd,
                viewport: CGSize(width: 1920, height: 1080), scale: 1,
                expected: rect(-240, -135, 2400, 1350)),
            Golden(name: "fit zoomed out", mode: .match, factor: 0.5, video: hd,
                viewport: CGSize(width: 1920, height: 1080), scale: 1,
                expected: rect(480, 270, 960, 540)),
            // Original size ignores the clip's size ratio to the display, and the factor
            // multiplies the one-to-one picture.
            Golden(name: "original size zoomed", mode: .none, factor: 1.5,
                video: CGSize(width: 1280, height: 720), viewport: laptop, scale: 2,
                expected: rect(-408, -98, 3840, 2160)),
            Golden(name: "stretch zoomed", mode: .stretch, factor: 2,
                video: CGSize(width: 1280, height: 720), viewport: CGSize(width: 1000, height: 1000),
                scale: 1, expected: rect(-500, -500, 2000, 2000)),
            // A tie that lands on the other side if the products are formed in another order.
            Golden(name: "rounding follows the renderer's operation order", mode: .match, factor: 1,
                video: CGSize(width: 1000, height: 1000), viewport: CGSize(width: 1001, height: 1001),
                scale: 1.5, expected: rect(0, 0, 1501, 1501)),
            Golden(name: "small clip, fit", mode: .match, factor: 1,
                video: CGSize(width: 64, height: 36), viewport: CGSize(width: 40, height: 40),
                scale: 1, expected: rect(0, 9, 40, 23)),
            Golden(name: "small clip, fill", mode: .fill, factor: 1,
                video: CGSize(width: 64, height: 36), viewport: CGSize(width: 40, height: 40),
                scale: 1, expected: rect(-16, 0, 71, 40)),
            Golden(name: "small clip, original size zoomed", mode: .none, factor: 1.5,
                video: CGSize(width: 64, height: 36), viewport: CGSize(width: 40, height: 40),
                scale: 2, expected: rect(-56, -14, 192, 108)),
        ]
    }

    func testPictureRectEqualsTheCompatibilityLayout() {
        for item in golden {
            let actual = NativeVideoLayout.pictureRect(
                mode: item.mode, factor: item.factor, videoSize: item.video,
                viewport: item.viewport, backingScale: item.scale)
            XCTAssertEqual(actual, item.expected, item.name)
        }
    }

    func testNonFiniteAndNonPositiveFactorsBehaveAsOne() {
        let video = CGSize(width: 1920, height: 1080)
        let viewport = CGSize(width: 1512, height: 982)
        let plain = NativeVideoLayout.pictureRect(
            mode: .fill, factor: 1, videoSize: video, viewport: viewport, backingScale: 2)
        XCTAssertEqual(plain, rect(-234, 0, 3492, 1964))
        for factor in [0, -3, -0.0, Double.nan, .infinity, -.infinity] {
            XCTAssertEqual(
                NativeVideoLayout.pictureRect(
                    mode: .fill, factor: factor, videoSize: video, viewport: viewport,
                    backingScale: 2),
                plain, "factor \(factor)")
            XCTAssertEqual(NativeVideoLayout.normalizedFactor(factor), 1)
        }
        // A display scale that is not a number is as unusable as a factor that is not.
        XCTAssertEqual(
            NativeVideoLayout.pictureRect(
                mode: .fill, factor: 1, videoSize: video, viewport: viewport, backingScale: 0),
            NativeVideoLayout.pictureRect(
                mode: .fill, factor: 1, videoSize: video, viewport: viewport, backingScale: 1))
    }

    func testDegenerateSizesAndAbsurdFactorsStayValid() {
        let empty = NativeVideoLayout.pictureRect(
            mode: .match, factor: 1, videoSize: .zero, viewport: .zero, backingScale: 2)
        XCTAssertGreaterThanOrEqual(empty.width, 1)
        XCTAssertGreaterThanOrEqual(empty.height, 1)
        let huge = NativeVideoLayout.pictureRect(
            mode: .fill, factor: 1e300, videoSize: CGSize(width: 1920, height: 1080),
            viewport: CGSize(width: 1920, height: 1080), backingScale: 2)
        XCTAssertLessThanOrEqual(huge.width, Int(Int32.max))
        XCTAssertGreaterThanOrEqual(huge.width, 1)
        let nan = NativeVideoLayout.pictureRect(
            mode: .fill, factor: 1, videoSize: CGSize(width: CGFloat.nan, height: 10),
            viewport: CGSize(width: 100, height: 100), backingScale: 1)
        XCTAssertGreaterThanOrEqual(nan.width, 1)
    }

    func testTheDefaultPlacementIsTheGravityItReplaces() {
        let viewport = CGSize(width: 1512, height: 982)
        let video = CGSize(width: 1920, height: 1080)
        let expected: [(NativeVideoScalingMode, AVLayerVideoGravity)] = [
            (.fill, .resizeAspectFill), (.match, .resizeAspect), (.stretch, .resize),
        ]
        for (mode, gravity) in expected {
            // Whether or not the size is known: the layer fills the display and
            // AVFoundation places the picture, which also follows a rotation.
            for size in [nil, video] {
                XCTAssertEqual(
                    NativeVideoLayout.placement(
                        mode: mode, factor: 1, videoSize: size, viewport: viewport,
                        backingScale: 2),
                    .gravity(gravity), "\(mode) \(size.map { "\($0)" } ?? "without a size")")
            }
        }
        // The factor only normalises to one when it is unusable; 1 itself is the default.
        XCTAssertEqual(
            NativeVideoLayout.placement(
                mode: .fill, factor: .nan, videoSize: nil, viewport: viewport, backingScale: 2),
            .gravity(.resizeAspectFill))
    }

    /// The native player has no blurred backdrop: Fit with blurred backdrop is plain Fit here, with
    /// the picture exactly where Fit puts it and black bars.
    func testFitWithBlurredBackdropIsLaidOutAsFit() {
        let viewport = CGSize(width: 3440, height: 1440)
        let video = CGSize(width: 3840, height: 2160)
        for factor in [1.0, 0.8] {
            XCTAssertEqual(
                NativeVideoLayout.pictureRect(
                    mode: .matchBlurred, factor: factor, videoSize: video, viewport: viewport,
                    backingScale: 2),
                NativeVideoLayout.pictureRect(
                    mode: .match, factor: factor, videoSize: video, viewport: viewport,
                    backingScale: 2))
            XCTAssertEqual(
                NativeVideoLayout.placement(
                    mode: .matchBlurred, factor: factor, videoSize: video, viewport: viewport,
                    backingScale: 2),
                NativeVideoLayout.placement(
                    mode: .match, factor: factor, videoSize: video, viewport: viewport,
                    backingScale: 2))
        }
    }

    func testOriginalSizeAndScaleFactorsWaitForThePicturesSize() {
        let viewport = CGSize(width: 1512, height: 982)
        for (mode, factor) in [
            (NativeVideoScalingMode.none, 1.0), (.fill, 1.25), (.match, 0.5), (.stretch, 2),
        ] {
            XCTAssertEqual(
                NativeVideoLayout.placement(
                    mode: mode, factor: factor, videoSize: nil, viewport: viewport,
                    backingScale: 2),
                .pending, "\(mode) x\(factor)")
            XCTAssertEqual(
                NativeVideoLayout.placement(
                    mode: mode, factor: factor, videoSize: .zero, viewport: viewport,
                    backingScale: 2),
                .pending, "a zero size is no size: \(mode) x\(factor)")
        }
    }

    func testAFramePlacementIsThePictureRectInPoints() {
        let viewport = CGSize(width: 1512, height: 982)
        let video = CGSize(width: 1920, height: 1080)
        // Original size at 2x: 1920x1080 points, centred, overflowing the display.
        XCTAssertEqual(
            NativeVideoLayout.placement(
                mode: .none, factor: 1, videoSize: video, viewport: viewport, backingScale: 2),
            .frame(CGRect(x: -204, y: -49, width: 1920, height: 1080)))
        // Fit at x0.5 on a 1x display.
        XCTAssertEqual(
            NativeVideoLayout.placement(
                mode: .match, factor: 0.5, videoSize: video,
                viewport: CGSize(width: 1920, height: 1080), backingScale: 1),
            .frame(CGRect(x: 480, y: 270, width: 960, height: 540)))
    }

    // MARK: - A position in the room around the picture

    /// The renderer's own rule: the slack the display has left after the picture, negative
    /// when the picture overflows it, is divided by the fraction on each axis.
    func testAPositionDividesTheRoomTheWayTheRendererDoes() {
        let video = CGSize(width: 1920, height: 1080)
        let viewport = CGSize(width: 1000, height: 1000)
        // Fit: 1000x562.5 at x0, with 437.5 of room above and below it.
        let top = NativeVideoLayout.pictureRect(
            mode: .match, factor: 1, videoSize: video, viewport: viewport, backingScale: 1,
            pan: .init(x: 0, y: 0))
        XCTAssertEqual(top, rect(0, 0, 1000, 563))
        let bottom = NativeVideoLayout.pictureRect(
            mode: .match, factor: 1, videoSize: video, viewport: viewport, backingScale: 1,
            pan: .init(x: 1, y: 1))
        XCTAssertEqual(bottom, rect(0, 438, 1000, 563))
        XCTAssertEqual(
            NativeVideoLayout.pictureRect(
                mode: .match, factor: 1, videoSize: video, viewport: viewport, backingScale: 1,
                pan: .init(x: 0.5, y: 0.5)),
            NativeVideoLayout.pictureRect(
                mode: .match, factor: 1, videoSize: video, viewport: viewport, backingScale: 1))
        // Fill overflows sideways: 1778x1000, so a pan of 0 puts its left edge on the display's.
        let left = NativeVideoLayout.pictureRect(
            mode: .fill, factor: 1, videoSize: video, viewport: viewport, backingScale: 1,
            pan: .init(x: 0, y: 0.5))
        XCTAssertEqual(left.x, 0)
        let right = NativeVideoLayout.pictureRect(
            mode: .fill, factor: 1, videoSize: video, viewport: viewport, backingScale: 1,
            pan: .init(x: 1, y: 0.5))
        XCTAssertEqual(right.x, -778)
        // Stretch has no room, so no position moves it.
        XCTAssertEqual(
            NativeVideoLayout.pictureRect(
                mode: .stretch, factor: 1, videoSize: video, viewport: viewport, backingScale: 1,
                pan: .init(x: 0, y: 1)),
            rect(0, 0, 1000, 1000))
    }

    func testAnUnusablePositionIsHeldToTheEdgeOrTheMiddleAsTheRendererDoes() {
        let video = CGSize(width: 1920, height: 1080)
        let viewport = CGSize(width: 1000, height: 1000)
        func rectAt(_ x: Double, _ y: Double) -> NativeVideoLayout.PixelRect {
            NativeVideoLayout.pictureRect(
                mode: .match, factor: 1, videoSize: video, viewport: viewport, backingScale: 1,
                pan: .init(x: x, y: y))
        }
        XCTAssertEqual(rectAt(-3, -3), rectAt(0, 0))
        XCTAssertEqual(rectAt(7, 7), rectAt(1, 1))
        XCTAssertEqual(rectAt(.nan, .infinity), rectAt(0.5, 0.5))
    }

    func testAPositionNeedsAnExplicitFrameBecauseGravityCentres() {
        let viewport = CGSize(width: 1000, height: 1000)
        let video = CGSize(width: 1920, height: 1080)
        XCTAssertEqual(
            NativeVideoLayout.placement(
                mode: .match, factor: 1, videoSize: video, viewport: viewport, backingScale: 1,
                pan: .init(x: 0.5, y: 0.5)),
            .gravity(.resizeAspect))
        XCTAssertEqual(
            NativeVideoLayout.placement(
                mode: .match, factor: 1, videoSize: video, viewport: viewport, backingScale: 1,
                pan: .init(x: 0.5, y: 0)),
            .frame(CGRect(x: 0, y: 0, width: 1000, height: 563)))
        // The size is not known yet, so there is nothing to place.
        XCTAssertEqual(
            NativeVideoLayout.placement(
                mode: .match, factor: 1, videoSize: nil, viewport: viewport, backingScale: 1,
                pan: .init(x: 0.5, y: 0)),
            .pending)
    }

    /// The Position sliders measure from the top (0 is the top edge) and a window's layer grows
    /// upward, so the layout's rectangle has to be flipped into it. Checked on pixels, because a
    /// frame that is numerically right in the wrong convention puts the picture at the bottom.
    func testAPictureAtTheTopEdgeIsDrawnAtTheTopOfAnUpwardGrowingLayer() throws {
        let viewport = CGSize(width: 40, height: 30)
        let rect = NativeVideoLayout.pictureRect(
            mode: .none, factor: 1, videoSize: CGSize(width: 20, height: 10),
            viewport: viewport, backingScale: 1, pan: .init(x: 0, y: 0))
        XCTAssertEqual(rect.y, 0, "the layout puts it on the top edge")

        let root = CALayer()
        root.frame = CGRect(origin: .zero, size: viewport)
        root.backgroundColor = CGColor(red: 0, green: 0, blue: 0, alpha: 1)
        let picture = CALayer()
        picture.backgroundColor = CGColor(red: 1, green: 0, blue: 0, alpha: 1)
        picture.frame = NativeVideoLayout.layerFrame(
            CGRect(x: rect.x, y: rect.y, width: rect.width, height: rect.height),
            viewportHeight: viewport.height)
        root.addSublayer(picture)

        let space = try XCTUnwrap(CGColorSpace(name: CGColorSpace.sRGB))
        let context = try XCTUnwrap(CGContext(
            data: nil, width: 40, height: 30, bitsPerComponent: 8, bytesPerRow: 40 * 4,
            space: space,
            bitmapInfo: CGBitmapInfo.byteOrder32Big.rawValue | CGImageAlphaInfo.premultipliedLast.rawValue))
        root.render(in: context)
        let image = try XCTUnwrap(context.makeImage())
        let data = try XCTUnwrap(image.dataProvider?.data as Data?)
        // Rows of a CGImage run from the top.
        func red(atRow row: Int) -> UInt8 { data[row * image.bytesPerRow + 5 * 4] }
        XCTAssertEqual(red(atRow: 2), 255, "the picture is at the top of the picture")
        XCTAssertEqual(red(atRow: 27), 0, "and not at the bottom")
    }

    func testALayerFrameKeepsItsSizeAndFlipsOnlyTheVerticalPlace() {
        XCTAssertEqual(
            NativeVideoLayout.layerFrame(CGRect(x: 3, y: 4, width: 20, height: 10), viewportHeight: 50),
            CGRect(x: 3, y: 36, width: 20, height: 10))
        // A picture taller than the display overflows both edges alike.
        XCTAssertEqual(
            NativeVideoLayout.layerFrame(CGRect(x: 0, y: -5, width: 10, height: 60), viewportHeight: 50),
            CGRect(x: 0, y: -5, width: 10, height: 60))
    }

    func testTheModeNumbersAreTheConfigurationsAndTheRenderers() {
        XCTAssertEqual(NativeVideoScalingMode(rawValue: 0), NativeVideoScalingMode.none)
        XCTAssertEqual(NativeVideoScalingMode(rawValue: 1), .stretch)
        XCTAssertEqual(NativeVideoScalingMode(rawValue: 2), .match)
        XCTAssertEqual(NativeVideoScalingMode(rawValue: 3), .fill)
        XCTAssertNil(NativeVideoScalingMode(rawValue: 4))
        XCTAssertEqual(BridgeScalingMode.none.layoutMode, NativeVideoScalingMode.none)
        XCTAssertEqual(BridgeScalingMode.stretch.layoutMode, .stretch)
        XCTAssertEqual(BridgeScalingMode.match.layoutMode, .match)
        XCTAssertEqual(BridgeScalingMode.fill.layoutMode, .fill)
    }
}
