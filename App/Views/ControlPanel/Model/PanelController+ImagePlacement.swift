import AppKit
import Foundation

/// Where a still image that this app packaged sits on one display: the inspector's Position on
/// screen card for a picture saved from pixiv or imported from disk.
///
/// A placement is the picture's position (0 to 1 on each axis) and its zoom (1 to 3), kept per
/// wallpaper and per display, and applies at once. It is never a draft.
struct ImagePlacementState: Equatable {
  let wallpaperID: String
  let displayID: String
  let displayTitle: String
  /// A generated image page on an enabled independent display; else `reason` says why not.
  let isSupported: Bool
  let reason: String?
  /// The saved position and zoom, or what the fit alone places when the user has not moved it:
  /// centred, except for Fill keeping the top, which starts at the top.
  let x: Double
  let y: Double
  let zoom: Double
  /// The user moved the picture; Reset to Image fit is offered.
  let isCustomized: Bool
  /// The fit in force: the applied `fit` property when the options are loaded, else the page's own.
  let fit: StillImageWallpaper.Fit?
  let imagePixelSize: CGSize?
  let imageAspectRatio: Double?
  /// The target display's shape, size in points and size in pixels; nil when no attached screen has
  /// the display's id.
  let displayAspectRatio: Double?
  let displayViewportSize: CGSize?
  let displayPixelSize: CGSize?
}

extension PanelController {
  /// The placement card for the selected wallpaper on the target display, or nil when nothing is
  /// selected. A wallpaper that is not an unmodified generated image page, or a display that cannot
  /// show one on its own, gives a card that says why.
  var imagePlacementState: ImagePlacementState? {
    _ = revisions.imagePlacement
    guard let id = store.appSnapshot.selectedWallpaperId else { return nil }
    let displayID = navigation.targetDisplayID
    let display = store.settingsSnapshot.displays.first { $0.displayId == displayID }
    let displaySupported = display.map { $0.enabled && $0.mode == .standalone } ?? false
    let installed = store.librarySnapshot.wallpapers.contains { $0.id == id }
    let info = installed ? imagePlacement.generatedImage(wallpaperID: id) : nil
    let custom = imagePlacement.placement(wallpaperID: id, displayID: displayID)
    var fit = info?.fit
    if let options = store.wallpaperOptionsSnapshot, options.wallpaperId == id,
      let property = options.properties.first(where: { $0.id == "fit" }),
      case .string(let value) = property.value,
      let applied = StillImageWallpaper.Fit(rawValue: value)
    {
      fit = applied
    }
    var aspect: Double?
    var viewport: CGSize?
    var pixels: CGSize?
    if let screen = DisplayGeometry.screen(displayID: displayID, title: display?.title ?? ""),
      screen.frame.height > 0
    {
      aspect = screen.frame.width / screen.frame.height
      viewport = screen.frame.size
      pixels = CGSize(
        width: screen.frame.width * screen.backingScaleFactor,
        height: screen.frame.height * screen.backingScaleFactor)
    }
    let reason: String? =
      !displaySupported
      ? L("Image placement requires an enabled independent display.")
      : info == nil
        ? L(
          "Image placement is available only for unmodified image pages generated by WallpaperMachine."
        ) : nil
    return ImagePlacementState(
      wallpaperID: id, displayID: displayID,
      displayTitle: displayTitles.resolved().title(display?.title ?? "", displayId: displayID),
      isSupported: info != nil && displaySupported, reason: reason, x: custom?.x ?? 0.5,
      y: custom?.y ?? (fit == .fillTop ? 0 : 0.5), zoom: custom?.zoom ?? 1,
      isCustomized: custom != nil, fit: fit, imagePixelSize: info?.imagePixelSize,
      imageAspectRatio: info?.imageAspectRatio, displayAspectRatio: aspect,
      displayViewportSize: viewport, displayPixelSize: pixels)
  }

  /// `imagePlacement`: moves and zooms the picture on one display. Leaves the banner alone and does
  /// not wait for the command queue. `x` and `y` are fractions from 0 to 1 and `zoom` is from 1 to 3;
  /// a value outside is refused. The display must be enabled and independent.
  ///
  /// Requests are sequenced per wallpaper and display (see `commitImagePlacement`).
  func setImagePlacement(
    _ wallpaperID: String, display displayID: String, x: Double, y: Double, zoom: Double
  ) async throws {
    try await run(.immediate) {
      let id = try installedWallpaperID(wallpaperID)
      try validatePlacementDisplay(displayID)
      guard zoom.isFinite, StillImagePlacement.zoomRange.contains(zoom) else {
        throw InvalidControlValue()
      }
      let placement = try StillImagePlacement(
        x: PanelValueRules.fraction(x), y: PanelValueRules.fraction(y), zoom: zoom)
      try await commitImagePlacement(placement, wallpaperID: id, displayID: displayID)
    }
  }

  /// `imagePlacementReset`: puts the picture back where Image fit alone places it.
  func resetImagePlacement(_ wallpaperID: String, display displayID: String) async throws {
    try await run(.immediate) {
      let id = try installedWallpaperID(wallpaperID)
      try validatePlacementDisplay(displayID)
      try await commitImagePlacement(nil, wallpaperID: id, displayID: displayID)
    }
  }

  /// A request that may need the page upgraded first suspends while the store prepares it, and a
  /// newer request for the same wallpaper and display may be made in that time. Each request takes
  /// a sequence number and goes ahead only if it is still the newest once the page is ready: the
  /// older one returns quietly, so a Reset can never lose to a cold placement it overtook.
  private func commitImagePlacement(
    _ placement: StillImagePlacement?, wallpaperID id: String, displayID: String
  ) async throws {
    let key = id + "\u{0}" + displayID
    imagePlacementRequestSequence &+= 1
    let requestSequence = imagePlacementRequestSequence
    imagePlacementRequests[key] = requestSequence
    defer {
      if imagePlacementRequests[key] == requestSequence { imagePlacementRequests[key] = nil }
    }
    guard try await imagePlacement.prepare(wallpaperID: id) != nil else {
      throw WallpaperActionError(
        message: L(
          "This wallpaper is not an unmodified image page generated by WallpaperMachine."))
    }
    guard imagePlacementRequests[key] == requestSequence else { return }
    try Task.checkCancellation()
    // Preparation suspends: reject a target that was removed or disabled in the meantime.
    _ = try installedWallpaperID(id)
    try validatePlacementDisplay(displayID)
    if let placement {
      try imagePlacement.set(placement, wallpaperID: id, displayID: displayID)
    } else {
      try imagePlacement.reset(wallpaperID: id, displayID: displayID)
    }
  }

  private func validatePlacementDisplay(_ displayID: String) throws {
    guard
      store.settingsSnapshot.displays.contains(where: {
        $0.displayId == displayID && $0.enabled && $0.mode == .standalone
      })
    else { throw InvalidControlValue() }
  }
}
